"""Read-only export of stored Mode A gap reports for the Phase 13 harness.

The authoritative source is the `gap_reports` table (what `GET /reports`
serves), joined to the clusters and rankings it was generated from. Nothing is
regenerated, re-ranked or written: every query is a SELECT and the session is
rolled back.

Everything a report says is **generated by ScholarLens** -- the gap text, the
directions, the model's confidence and its claim judgments. They are exported
under `generated` so the evaluation side can keep them apart from independent
evidence (later papers, surveys, expert ratings), which this export never
contains.

Deterministic: no wall-clock field, reports ordered by id, digests over
canonical JSON. Two exports of the same database are byte-identical.

    docker exec -i nlp-backend-1 python - < backend/app/explanation/export.py > export.json
"""

from __future__ import annotations

import json
import sys

from sqlalchemy import func, select
from sqlalchemy.orm import Session

EXPORT_SCHEMA = "scholarlens-gap-export/1"


class ExportError(ValueError):
    """A stored report cannot be exported with traceable evidence."""


def _evidence(report_id: int, items: object) -> list[dict]:
    if not isinstance(items, list) or not items:
        raise ExportError(f"report {report_id} has no evidence")
    rows = []
    for position, item in enumerate(items):
        if not isinstance(item, dict):
            raise ExportError(
                f"report {report_id} evidence[{position}] is not an object"
            )
        evidence_id, paper_id = item.get("id"), item.get("paper_id")
        if not isinstance(evidence_id, str) or not evidence_id.strip():
            raise ExportError(f"report {report_id} evidence[{position}] has no id")
        if isinstance(paper_id, bool) or not isinstance(paper_id, int):
            raise ExportError(
                f"report {report_id} evidence[{position}] has no paper_id"
            )
        rows.append(
            {
                "evidence_id": evidence_id,
                "paper_id": paper_id,
                "year": item.get("year"),
                "title": item.get("title"),
                "source_type": item.get("source_type"),
            }
        )
    return rows


def _claims(justification: dict | None) -> dict:
    return {
        name: {
            "basis": claim.get("basis"),
            "supported": claim.get("supported"),
            "evidence_ids": list(claim.get("evidence_ids") or []),
        }
        for name, claim in sorted((justification or {}).items())
        if isinstance(claim, dict)
    }


def export_reports(session: Session) -> dict:
    """Every stored report with its provenance. Raises `ExportError` on bad evidence."""
    from app.clustering.storage import list_clusters, members_for_cluster
    from app.core.pipeline import DerivedState, fingerprint
    from app.explanation.storage import list_reports, serialize_report
    from app.ingestion.corpus import Paper
    from app.ranking.signals import evidence_scope
    from app.ranking.storage import list_rankings

    clusters = {c.id: c for c in list_clusters(session)}
    rankings = list_rankings(session, max(len(clusters), 1))
    rank_of = {
        r.cluster_id: (position, r) for position, r in enumerate(rankings, start=1)
    }
    papers, min_year, max_year = session.execute(
        select(func.count(Paper.id), func.min(Paper.year), func.max(Paper.year))
    ).one()
    markers = {
        row.name: row.input_fingerprint for row in session.scalars(select(DerivedState))
    }

    reports = []
    for row in list_reports(session):
        cluster = clusters.get(row.cluster_id)
        if cluster is None:
            raise ExportError(
                f"report {row.id} points at missing cluster {row.cluster_id}"
            )
        if not isinstance(row.gap, str) or not row.gap.strip():
            raise ExportError(f"report {row.id} has no gap statement")
        evidence = _evidence(row.id, row.evidence)
        position, ranking = rank_of.get(row.cluster_id, (None, None))
        reports.append(
            {
                "report_id": row.id,
                "cluster_id": row.cluster_id,
                "created_at": row.created_at.isoformat() if row.created_at else None,
                "content_sha256": fingerprint(serialize_report(row)),
                "cluster_label": cluster.label,
                "cluster_paper_ids": sorted(
                    {m.paper_id for m in members_for_cluster(session, cluster.id)}
                ),
                "ranking": None
                if ranking is None
                else {
                    "rank": position,
                    "score": ranking.score,
                    "paper_count": ranking.mention_frequency,
                    "evidence_scope": evidence_scope(ranking.mention_frequency),
                },
                "evidence": evidence,
                "supporting_paper_ids": sorted({e["paper_id"] for e in evidence}),
                "generated": {
                    "gap": row.gap.strip(),
                    "suggested_directions": list(row.suggested_directions or []),
                    "model_confidence": row.confidence,
                    "provider": row.provider,
                    "model": row.model,
                    "claims": _claims(row.justification),
                },
            }
        )
    return {
        "export_schema": EXPORT_SCHEMA,
        "source": {
            "table": "gap_reports",
            "derived_state": {k: markers[k] for k in sorted(markers)},
        },
        "corpus": {"papers": papers, "min_year": min_year, "max_year": max_year},
        "reports": reports,
        "export_digest": fingerprint(reports),
    }


def main() -> int:
    from app.ingestion.corpus import get_engine

    with Session(get_engine()) as session:
        try:
            document = export_reports(session)
        finally:
            session.rollback()
    json.dump(document, sys.stdout, indent=1, ensure_ascii=False, sort_keys=True)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
