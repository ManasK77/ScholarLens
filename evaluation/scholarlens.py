"""Evaluate ScholarLens's own stored gap reports with the Phase 13 harness.

Input is the read-only export from `backend/app/explanation/export.py`
(schema `scholarlens-gap-export/1`). This module never reads the pipeline's
stores and never writes them.

What a stored report says -- its gap text, directions, model confidence and
claim judgments -- is **generated by ScholarLens**. It is carried into
`provenance.json` under `generated` for traceability and is never used as a
validation signal: the validity index comes only from independent evidence
(later papers, survey open problems, expert ratings) supplied by the caller.
Without that evidence each method is reported as unavailable.

    PYTHONPATH=. backend/.venv/bin/python -m evaluation.scholarlens \
        --export evaluation/output/scholarlens/export.json \
        --output-dir evaluation/output/scholarlens \
        [--future-papers F.json] [--surveys S.json] [--expert-scores E.csv]
"""

import argparse
import csv
import json
from pathlib import Path

from evaluation.cli import print_summary
from evaluation.models import SCORE_FIELDS
from evaluation.report import run_evaluation

EXPORT_SCHEMA = "scholarlens-gap-export/1"
ADAPTER_VERSION = "scholarlens-adapter/1"


def gap_id(report: dict) -> str:
    """Stable id: the cluster and the stored report it came from."""
    return f"scholarlens:cluster-{report['cluster_id']}:report-{report['report_id']}"


def validate_export(document: object) -> dict:
    """The export, or `ValueError` naming what is missing. Never substitutes.

    One error type for every malformed export, type errors included, so a
    caller has a single failure to handle.
    """
    if not isinstance(document, dict) or document.get("export_schema") != EXPORT_SCHEMA:
        raise ValueError(f"not a {EXPORT_SCHEMA} document")
    reports = document.get("reports")
    if not isinstance(reports, list) or not reports:
        raise ValueError("the export contains no reports")
    max_year = (document.get("corpus") or {}).get("max_year")
    if isinstance(max_year, bool) or not isinstance(max_year, int):
        raise ValueError("the export has no corpus max_year to use as the cutoff")  # noqa: TRY004
    for position, report in enumerate(reports):
        label = f"reports[{position}]"
        if not isinstance(report, dict):
            raise ValueError(f"{label} is not an object")  # noqa: TRY004
        for key in ("report_id", "cluster_id"):
            if isinstance(report.get(key), bool) or not isinstance(
                report.get(key), int
            ):
                raise ValueError(f"{label} has no integer {key}")  # noqa: TRY004
        gap = (report.get("generated") or {}).get("gap")
        if not isinstance(gap, str) or not gap.strip():
            raise ValueError(f"{label} has no generated gap statement")
        evidence = report.get("evidence")
        if not isinstance(evidence, list) or not evidence:
            raise ValueError(f"{label} has no evidence")
        for item in evidence:
            if (
                not isinstance(item, dict)
                or not item.get("evidence_id")
                or not isinstance(item.get("paper_id"), int)
            ):
                raise ValueError(f"{label} has malformed evidence: {item!r}"[:200])
    return document


def gaps_input(document: dict, cutoff_year: int | None = None) -> list[dict]:
    """Harness `gaps.json` rows. No relevance labels exist, so none are given.

    The default cutoff is the newest publication year in the corpus the
    reports were built from: only papers published after everything the
    pipeline read can count as later evidence.
    """
    cutoff = cutoff_year if cutoff_year is not None else document["corpus"]["max_year"]
    return [
        {
            "gap_id": gap_id(report),
            "description": report["generated"]["gap"],
            "cutoff_year": cutoff,
            # Unlabelled (D-13-04): `[]` would assert "no relevant later
            # papers", a label nobody has assigned.
            "relevant_future_paper_ids": None,
        }
        for report in sorted(document["reports"], key=lambda r: r["report_id"])
    ]


def provenance(document: dict, cutoff_year: int) -> dict:
    return {
        "adapter_version": ADAPTER_VERSION,
        "export_schema": document["export_schema"],
        "export_digest": document.get("export_digest"),
        "source": document.get("source"),
        "corpus": document["corpus"],
        "cutoff_year": cutoff_year,
        "note": "`generated` is ScholarLens's own output (model-written text, "
        "model confidence, model claim judgments). It is not independent "
        "validation and is not used by any evaluation metric.",
        "gaps": {
            gap_id(report): {
                "report_id": report["report_id"],
                "cluster_id": report["cluster_id"],
                "cluster_label": report.get("cluster_label"),
                "created_at": report.get("created_at"),
                "content_sha256": report.get("content_sha256"),
                "ranking": report.get("ranking"),
                "supporting_paper_ids": sorted(
                    {e["paper_id"] for e in report["evidence"]}
                ),
                "evidence_ids": [e["evidence_id"] for e in report["evidence"]],
                "generated": report["generated"],
            }
            for report in sorted(document["reports"], key=lambda r: r["report_id"])
        },
    }


def write_rating_template(path: Path, gaps: list[dict]) -> None:
    """One unrated row per gap. Unrated rows are skipped, never scored."""
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["gap_id", "rater_id", *SCORE_FIELDS, "notes"])
        for gap in gaps:
            writer.writerow([gap["gap_id"], "", "", "", "", "", ""])


def _dump(path: Path, value) -> None:
    path.write_text(
        json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def run(
    export_path: Path,
    output_dir: Path,
    *,
    future_papers: Path | None = None,
    surveys: Path | None = None,
    expert_scores: Path | None = None,
    cutoff_year: int | None = None,
    similarity_threshold: float = 0.2,
) -> dict:
    document = validate_export(json.loads(export_path.read_text(encoding="utf-8")))
    gaps = gaps_input(document, cutoff_year)
    output_dir.mkdir(parents=True, exist_ok=True)
    _dump(output_dir / "gaps.json", gaps)
    _dump(output_dir / "provenance.json", provenance(document, gaps[0]["cutoff_year"]))
    write_rating_template(output_dir / "expert-scores-template.csv", gaps)
    return run_evaluation(
        output_dir / "gaps.json",
        future_papers,
        surveys,
        expert_scores,
        output_dir / "evaluation-report.json",
        similarity_threshold,
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Evaluate stored ScholarLens gap reports"
    )
    parser.add_argument("--export", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--future-papers", type=Path)
    parser.add_argument("--surveys", type=Path)
    parser.add_argument("--expert-scores", type=Path)
    parser.add_argument("--cutoff-year", type=int)
    parser.add_argument("--similarity-threshold", type=float, default=0.2)
    args = parser.parse_args()
    report = run(
        args.export,
        args.output_dir,
        future_papers=args.future_papers,
        surveys=args.surveys,
        expert_scores=args.expert_scores,
        cutoff_year=args.cutoff_year,
        similarity_threshold=args.similarity_threshold,
    )
    print_summary(report, args.output_dir / "evaluation-report.json")


if __name__ == "__main__":
    main()
